async (page) => {
  const origin = "http://127.0.0.1:8768";
  const status = await (await page.request.get(origin + "/api/status")).json();
  if (status.collector.status !== "isolated_test") throw new Error("isolated fixture required");
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(origin);
  await page.getByRole("button", { name: "设置", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "账号池", exact: true }).click();
  await dialog.getByLabel("账号名称", { exact: true }).fill("UI 隔离账号 A");
  await dialog.getByLabel("API Base URL", { exact: true }).fill("https://test.invalid");
  await dialog.getByLabel("API Key", { exact: true }).fill("ui-fixture-not-a-real-key");
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await dialog.getByText("已保存", { exact: true }).waitFor();
  let settings = await (await page.request.get(origin + "/api/settings")).json();
  const account = settings.key_pool.find((item) => item.label === "UI 隔离账号 A");
  if (!account || account.base_url !== "https://test.invalid/v1") throw new Error("pool create failed");
  if (/credential_ref|rate_key|ui-fixture-not-a-real-key/.test(JSON.stringify(settings))) throw new Error("secret exposure");
  if (await dialog.getByLabel("API Key", { exact: true }).inputValue()) throw new Error("key not cleared");
  await dialog.getByLabel("账号名称", { exact: true }).fill("UI 隔离账号 A 已编辑");
  await dialog.getByLabel("启用账号", { exact: true }).uncheck();
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await dialog.getByText("已保存", { exact: true }).waitFor();
  await dialog.getByText("已停用", { exact: true }).waitFor();
  await page.screenshot({ path: "runtime/key-pool-settings-desktop.png" });
  await dialog.getByRole("button", { name: "精准模型", exact: true }).click();
  await dialog.getByLabel("UI 隔离账号 A 已编辑（已停用）", { exact: true }).check();
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await dialog.getByText("已保存", { exact: true }).waitFor();
  await dialog.getByRole("button", { name: "业务与背景", exact: true }).click();
  await dialog.getByRole("button", { name: "直达分析", exact: true }).click();
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await dialog.getByText("已保存", { exact: true }).waitFor();
  settings = await (await page.request.get(origin + "/api/settings")).json();
  if (settings.general.analysis_mode !== "direct" || settings.general.analysis_enabled) throw new Error("mode save failed");
  if (!settings.models.analysis.pool_ids.includes(account.id)) throw new Error("role assignment failed");
  await dialog.getByRole("button", { name: "账号池", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "runtime/key-pool-settings-mobile.png" });
  const dimensions = await dialog.evaluate((node) => ({ width: node.clientWidth, scroll: node.scrollWidth, right: node.getBoundingClientRect().right, viewport: innerWidth }));
  if (dimensions.scroll > dimensions.width + 1 || dimensions.right > dimensions.viewport) throw new Error("dialog overflow");
  await dialog.getByRole("button", { name: "关闭设置", exact: true }).click();
  if (errors.length) throw new Error("page errors");
  return { create: true, edit: true, disable: true, role_assignment: true, direct_mode: true, secret_redaction: true, screenshots: 2, mobile_overflow: false, page_errors: errors.length };
}
