async (page) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const check = (value, message) => { if (!value) throw new Error(message); };
  const post = path => page.request.post('http://127.0.0.1:8768' + path, { headers: {'X-Live-Assistant': '1'} });
  await page.setViewportSize({width: 1440, height: 900});
  await page.goto('http://127.0.0.1:8768');
  await page.getByRole('button', {name: /模拟Markdown观众/}).click();
  await page.locator('.analysis-markdown').waitFor();
  check((await page.locator('.analysis-markdown > :first-child').innerText()).startsWith('主播直接说：'), 'Opening must be first');
  check(await page.locator('.analysis-markdown script, .analysis-markdown img, .analysis-markdown a').count() === 0, 'Unsafe markup rendered');
  check(!await page.evaluate(() => window.markdownInjected), 'Script executed');
  check(await page.getByRole('button', {name:'有效客户', exact:true}).isDisabled(), 'Scoring filter should be dormant');
  check(await page.locator('.analysis-content .unrated').innerText() === '暂无星级评估', 'Missing unscored fallback');
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.getByRole('button', {name:'复制提词', exact:true}).click();
  check(await page.evaluate(() => navigator.clipboard.readText()) === '每天大概有多少次订单查询？', 'Copy only spoken opening');
  await page.screenshot({path:'runtime/markdown-ui-20260909/desktop.png'});
  await page.getByRole('button', {name: /模拟旧版观众/}).click();
  await page.locator('.script-section p').waitFor();
  check((await page.locator('.script-section p').innerText()).length > 0, 'Legacy result compatibility');
  await page.getByRole('button', {name: /模拟Markdown观众/}).click();
  check((await (await post('/fixture/start')).json()).started, 'Start preview fixture');
  await page.locator('.markdown-preview .analysis-markdown').waitFor();
  check((await page.locator('.analysis-content').innerText()).includes('尚未保存'), 'Preview status missing');
  check(await page.locator('.analysis-markdown').count() === 2, 'Keep previous result during stream');
  check(!(await page.locator('.analysis-content').innerText()).includes('never-show-this-reasoning'), 'Reasoning leaked');
  await post('/fixture/release');
  await page.waitForFunction(() => !document.querySelector('.markdown-preview') && document.querySelector('.analysis-markdown')?.textContent.includes('更新后的测试提词'));
  await post('/fixture/start?fail=true');
  await page.locator('.markdown-preview').waitFor();
  await post('/fixture/release');
  await page.waitForFunction(() => !document.querySelector('.markdown-preview'));
  check((await page.locator('.analysis-markdown').innerText()).includes('更新后的测试提词'), 'Failed stream removed previous success');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button', {name:'提词', exact:true}).click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile horizontal overflow');
  await page.screenshot({path:'runtime/markdown-ui-20260909/mobile.png'});
  check(errors.length === 0, errors.join('\n'));
  return {passed:true, checks:'Markdown opening, copy, XSS, legacy, streaming preview/success/failure, mobile', errors};
}
